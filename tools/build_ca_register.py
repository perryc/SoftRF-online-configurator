#!/usr/bin/env python3
"""Build ca_register.js from Transport Canada's Canadian Civil Aircraft Register.

Download https://wwwapps.tc.gc.ca/saf-sec-sur/2/ccarcs-riacc/download/ccarcsdb.zip
(refreshed daily), unzip, then:  python3 tools/build_ca_register.py carscurr.txt

Output maps each mark (without "C-") to its model, with the 24-bit Mode S
address included explicitly only where the C-F/C-G formula does not apply
(three-letter C-I ultralight marks and historic allocations).
"""
import csv, json, sys, datetime

def formula(mark):
    if len(mark) != 4 or mark[0] not in "FG" or not mark[1:].isalpha():
        return None
    off = (0 if mark[0] == "F" else 17576) + (ord(mark[1]) - 65) * 676 \
        + (ord(mark[2]) - 65) * 26 + (ord(mark[3]) - 65)
    return 0xC00001 + off

def main(path, out="ca_register.js"):
    rows = [r for r in csv.reader(open(path, encoding="latin-1")) if len(r) >= 47 and r[0].strip()]
    table = {}
    for r in rows:
        mark, bits = r[0].strip().upper(), r[42].strip()
        if len(bits) != 24:
            continue
        icao = int(bits, 2)
        model = " ".join(r[4].split()).upper()[:20]
        table[mark] = model if formula(mark) == icao else f"{icao:06X}|{model}"
    js = ("// Canadian Civil Aircraft Register (Transport Canada carscurr.txt), generated by tools/build_ca_register.py\n"
          "// mark -> \"MODEL\" (address from the C-F/C-G formula) or \"HEX|MODEL\"\n"
          f"window.CA_REGISTER_DATE=\"{datetime.date.today().isoformat()}\";\n"
          f"window.CA_REGISTER={json.dumps(table, separators=(',', ':'))};\n")
    open(out, "w").write(js)
    print(f"{len(table)} aircraft, {sum('|' in v for v in table.values())} with explicit address, {len(js)} bytes -> {out}")

if __name__ == "__main__":
    main(*sys.argv[1:])
